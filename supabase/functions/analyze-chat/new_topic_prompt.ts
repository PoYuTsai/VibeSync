/**
 * 切入角度輪替（2026-08-19 A/B 驗證）：同一個對象連按數次會拿到幾乎一樣的
 * 五題，因為輸入不變、輸出就不變。每次生成換一個彼此語意距離很遠的角度，
 * 是零額外呼叫、零延遲的解法。
 *
 * 兩次獨立 n=40 配對實測（都跟「拿掉 prompt 示範句」綁在一起做）：
 * 跨輪重複 24→14、28→12（合計 65%→33%），實質問句 51→36，
 * 撞已知興趣與轉折骨架持平。單獨做任一邊都無效——示範句還在時角度壓不過它，
 * 拿掉示範句而沒有角度則會退回死抓她的興趣清單。
 */
export const NEW_TOPIC_ANGLES = [
  "作息與睡眠",
  "食物與口味的固執",
  "花錢的習慣",
  "小時候與長大的地方",
  "住的環境與鄰居",
  "工作以外的身分",
  "收集癖或怪習慣",
  "對某件小事的偏激意見",
  "無厘頭的假設情境",
  "最近一件蠢事",
] as const;

/**
 * 用 requestId 選角度：同一次生成 replay 必須拿到同一個角度（扣費與
 * ledger 契約要求同 requestId 結果一致），不同次生成才換。
 */
export function pickNewTopicAngle(requestId: string): string {
  let sum = 0;
  for (const ch of requestId) sum = (sum + ch.charCodeAt(0)) % 100003;
  return NEW_TOPIC_ANGLES[sum % NEW_TOPIC_ANGLES.length];
}

const SITUATION_LABELS: Record<NewTopicSituation, string> = {
  went_cold: "聊天冷掉了（對方最近回得少或已讀）",
  after_date: "剛約完會（想自然延續餘溫）",
  stuck: "聊天卡住了（不知道接什麼新話題）",
  warm_up: "想讓關係升溫（想多一點個人感）",
};

/**
 * 三段素材分隔明確（§2）：只有作戰板可當對方事實。缺席的段落明說
 * 「沒有提供」，逼模型走低假設路線而不是腦補。
 */
export function buildNewTopicUserPrompt(input: {
  partnerSummary: string | null;
  effectiveStyleContext: string | null;
  situation: NewTopicSituation | null;
  requestId?: string;
}): string {
  const sections: string[] = [];

  sections.push("## 對方作戰板（唯一可當對方事實的來源）");
  sections.push(
    input.partnerSummary ??
      "（沒有提供對方資料：用開放式、低假設的話題，不要猜測對方的興趣）",
  );

  sections.push("");
  sections.push("## 關於我（用戶本人的風格與興趣，只能做自我揭露）");
  sections.push(
    input.effectiveStyleContext ??
      "（沒有提供：語氣自然即可，不要編造用戶的個人素材）",
  );

  sections.push("");
  sections.push("## 目前狀況（只影響節奏與語氣）");
  sections.push(
    input.situation !== null
      ? SITUATION_LABELS[input.situation]
      : "（沒有選擇：當作日常重啟，自然、低壓）",
  );

  if (input.requestId) {
    sections.push("");
    sections.push(`## 這次的切入角度：${pickNewTopicAngle(input.requestId)}`);
    sections.push(
      "五題裡至少兩題要從這個角度長出來，其餘自由。這是為了讓同一個對象每次生成不會撞題，" +
        "不是題目本身——不要把角度的名字寫進訊息裡。",
    );
  }

  sections.push("");
  sections.push("請依系統規則產出恰好五個新話題的 JSON。");
  return sections.join("\n");
}

export function buildNewTopicRepairPrompt(rawText: string): string {
  const clippedRawText = rawText.trim().slice(0, 7000);
  return [
    "以下是上一次新話題 AI 回覆，格式不穩或不符合 schema。",
    "請只修成合法 JSON；如果原文有 code fence、前後說明、欄位缺漏、key 名稱不對，全部整理成指定 schema。",
    "如果部分欄位缺漏，請用原文可推得出的最保守內容補齊；不要編造原文沒有的素材。",
    "",
    "原始回覆：",
    clippedRawText || "(empty)",
  ].join("\n");
}
