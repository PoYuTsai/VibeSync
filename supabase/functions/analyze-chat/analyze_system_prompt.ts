function buildVisionContent(
  textContent: string,
  images: ImageData[],
): Array<
  {
    type: string;
    text?: string;
    source?: { type: string; media_type: string; data: string };
  }
> {
  const content: Array<
    {
      type: string;
      text?: string;
      source?: { type: string; media_type: string; data: string };
    }
  > = [];

  // 先加入圖片（按 order 排序）
  const sortedImages = [...images].sort((a, b) => a.order - b.order);
  for (const img of sortedImages) {
    content.push({
      type: "image",
      source: {
        type: "base64",
        media_type: img.mediaType,
        data: img.data,
      },
    });
  }

  // 最後加入文字內容
  content.push({
    type: "text",
    text: textContent,
  });

  return content;
}

