/// 不會衝過終點的曲線（back／elastic 天生會，另外處理）。
const _monotonic = <String>[
  'power1Out',
  'power2Out',
  'power3Out',
  'power4Out',
  'power2In',
  'power2InOut',
  'expoOut',
  'circOut',
  'sineOut',
];

void main() {
  test('取樣點逐一對上真的 GSAP（容差 1e-9）', () {
    expect(_curves.keys.toSet(), _gsapReference.keys.toSet(),
        reason: '對照表與曲線表不同步');

    for (final entry in _curves.entries) {
      final expected = _gsapReference[entry.key]!;
      expect(expected.length, _samplePoints.length);
      for (var i = 0; i < _samplePoints.length; i++) {
        final p = _samplePoints[i];
        expect(
          entry.value.transform(p),
          closeTo(expected[i], 1e-9),
          reason: '${entry.key} 在 p=$p 偏離 GSAP',
        );
      }
    }
  });

  test('每條曲線都從 0 出發、在 1 收斂', () {
    for (final entry in _curves.entries) {
      expect(entry.value.transform(0), 0, reason: entry.key);
      expect(entry.value.transform(1), 1, reason: entry.key);
    }
  });

  test('非彈性曲線全程單調遞增', () {
    for (final name in _monotonic) {
      final curve = _curves[name]!;
      var previous = curve.transform(0);
      for (var i = 1; i <= 200; i++) {
        final value = curve.transform(i / 200);
        expect(value, greaterThanOrEqualTo(previous), reason: '$name 在 ${i / 200} 回頭了');
        previous = value;
      }
    }
  });

  test('back.out 會衝過 1 再收回來（GSAP overshoot 1.70158）', () {
    final peak = <double>[
      for (var i = 0; i <= 200; i++) GsapEase.backOut.transform(i / 200),
    ].reduce((a, b) => a > b ? a : b);
    expect(peak, greaterThan(1.0));
    expect(GsapEase.backOut.transform(1), 1);
    // 預設 overshoot 的峰值約 1.1；換成 0 就該退化成不衝過頭。
    expect(peak, closeTo(1.1, 0.001));
    const noOvershoot = GsapBackOut(0);
    for (var i = 0; i <= 200; i++) {
      expect(noOvershoot.transform(i / 200), lessThanOrEqualTo(1.0));
    }
  });

  test('elastic.out 可調 amplitude/period，且仍收在 1', () {
    const wave = GsapElasticOut(amplitude: 1, period: 0.45);
    // 對照真的 GSAP：gsap.parseEase('elastic.out(1,0.45)')
    expect(wave.transform(0.05), closeTo(0.4583247796, 1e-9));
    expect(wave.transform(0.10), closeTo(0.9131759112, 1e-9));
    expect(wave.transform(0.25), closeTo(1.1661157561, 1e-9));
    expect(wave.transform(1), 1);
  });

  test('power 系列的 GSAP 命名位移沒有搞反', () {
    // GSAP：power1 是二次式、power2 是三次式。
    expect(GsapEase.power1Out.transform(0.5), closeTo(0.75, 1e-12));
    expect(GsapEase.power2Out.transform(0.5), closeTo(0.875, 1e-12));
    expect(GsapEase.power3Out.transform(0.5), closeTo(0.9375, 1e-12));
    expect(GsapEase.power4Out.transform(0.5), closeTo(0.96875, 1e-12));
  });
}
